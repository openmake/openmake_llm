export function showBanner(version: string): void {
    const gradient = [
        chalk.hex('#FF6B6B'),
        chalk.hex('#FF8E53'),
        chalk.hex('#FFC947'),
        chalk.hex('#7BED9F'),
        chalk.hex('#70A1FF'),
        chalk.hex('#5F27CD')
    ];

    const lines = BANNER.split('\n');
    lines.forEach((line, index) => {
        const colorIndex = Math.floor((index / lines.length) * gradient.length);
        console.log(gradient[Math.min(colorIndex, gradient.length - 1)](line));
    });

    console.log(chalk.gray.italic(`\n  AI 어시스턴트 v${version}`));
    console.log(chalk.gray('  Powered by OpenMake\n'));
}






